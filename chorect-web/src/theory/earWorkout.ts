import { Progression, TrainingMode } from "./eartraining";

/** Real-song ear-training workout: ONE 4-month curriculum, merged and expanded by
 *  Claude from Nadav's ChatGPT material (the two curriculum PDFs + the full
 *  203-page conversation — digest: docs/ear-training-conversation-digest.md).
 *
 *  4 months × 4 weeks × 4 sessions = 64 song-sessions. Every session is a REAL
 *  song run through the same 45-minute frame; synthetic progressions are
 *  train-ride work, never a session. Each MONTH introduces exactly one new
 *  listening objective; harmony, melody, bass, harmonization and prediction are
 *  trained EVERY week (spiral), only the complexity rises.
 *  Mirror of Kotlin EarWorkout.kt. */

export interface WorkoutSong { title: string; artist: string; version?: string; }

export interface WorkoutSession {
  number: number;               // 1..64
  title: string;
  song: WorkoutSong | null;
  songNote?: string;
  /** Function/structure to notice. */
  focus: string;
  /** The quality discrimination this session trains (the real bottleneck). */
  quality: string;
  /** Stage-appropriate melody-playback goal. */
  melody: string;
  /** Constrained harmonization task. */
  harmonization: string;
  passGoal: string;
  /** Appendix answer — keep hidden until you've attempted. */
  spoiler?: string;
  /** Set when the answer is a clean 4-bar diatonic loop the app can play. */
  loop?: Progression;
}

export interface WorkoutWeek {
  week: number;                 // 1..16
  month: number;                // 1..4
  title: string;
  /** Predict-the-next-FUNCTION drill for this week. */
  prediction: string;
  /** Arrangement details that must NOT count against you this week. */
  notGraded: string[];
  sessions: WorkoutSession[];
}

export interface WorkoutExam { timeLimit: string; requirements: string[]; passStandard: string; }

export interface WorkoutMonth {
  number: number;
  title: string;
  objective: string;
  vocabulary: string;
  harmonizationRule: string;
  melodyStage: string;
  trainFocus: string;
  project: string;
  exam: WorkoutExam;
}

