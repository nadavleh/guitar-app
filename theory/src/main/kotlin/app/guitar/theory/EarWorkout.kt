package app.guitar.theory

/** Real-song ear-training workout: ONE 12-month curriculum, merged and expanded by
 *  Claude from Nadav's ChatGPT material (the two curriculum PDFs + the full
 *  203-page conversation). Digest: docs/ear-training-conversation-digest.md.
 *
 *  12 months × 4 weeks × 4 sessions = 192 song-sessions, which is the timeline the
 *  conversation itself settled on (≈3 h/week = four 45-minute sessions). Every
 *  session is a REAL song run through the same 45-minute frame ([SESSION_FRAME]);
 *  synthetic progressions are train-ride work ([TRAIN_DRILLS]), never a session.
 *  Each month has ONE new listening objective; harmony, melody, bass,
 *  harmonization and prediction are trained EVERY week (spiral), only the
 *  complexity rises. Advance by passing the month exam, not by the calendar.
 *
 *  Mirrored in chorect-web earWorkout.ts. */

/** A named recording. [version] pins the performance the exercise was built on. */
data class WorkoutSong(val title: String, val artist: String, val version: String? = null)

/** One 45-minute session on one song. [song] is null for student-choice/exam
 *  sessions ([songNote] then says what to pick). */
data class WorkoutSession(
    val number: Int,        // 1..192
    val title: String,
    val song: WorkoutSong?,
    val songNote: String? = null,
    /**
     * Short scope caveat shown on the card — e.g. "First 8 bars only". Set ONLY where this
     * session's target genuinely differs from its month's [WorkoutMonth.scope] (an excerpt
     * bound, a required version). Empty for the normal case — the month card already
     * displays the month scope, so it is not echoed per session.
     */
    val caveat: String = "",
    /** Function/structure to notice. */
    val focus: String,
    /** The quality discrimination this session trains (the real bottleneck). */
    val quality: String,
    /** Stage-appropriate melody-playback goal. */
    val melody: String,
    /** Constrained harmonization task. */
    val harmonization: String,
    val passGoal: String,
    /** Appendix answer — keep hidden until you've attempted. */
    val spoiler: String = "",
    /** Set when the answer is a clean 4-bar diatonic loop the app can play. */
    val loop: Progression? = null,
)

/** One week: a single listening objective + 4 sessions + the week's prediction
 *  drill and grading boundaries. */
data class WorkoutWeek(
    val week: Int,          // 1..48
    val month: Int,         // 1..12
    val title: String,
    /** Predict-the-next-FUNCTION drill for this week (unfamiliar song). */
    val prediction: String,
    /** Arrangement details that must NOT count against you this week. */
    val notGraded: List<String>,
    val sessions: List<WorkoutSession>,
) {
    init { require(sessions.size == 4) { "week $week must have 4 sessions, got ${sessions.size}" } }
}

/** A month-end examination. */
data class WorkoutExam(val timeLimit: String, val requirements: List<String>, val passStandard: String)

/** One month: its single new objective, harmonization level, train-ride focus,
 *  monthly transcription project and exam. */
data class WorkoutMonth(
    val number: Int,
    val title: String,
    val phase: String,
    val objective: String,
    val vocabulary: String,
    /**
     * How much of a song you're expected to call this month, in one short clause. Shown on
     * the month card (visible even when the card is folded), so the answer to "how much of
     * this am I supposed to get?" is always one glance away.
     */
    val scope: String,
    val harmonizationRule: String,
    val melodyStage: String,
    /** Which [TRAIN_DRILLS] categories to run on train rides this month. */
    val trainFocus: String,
    /** The once-a-month complete-transcription graduation project. */
    val project: String,
    val exam: WorkoutExam,
)

